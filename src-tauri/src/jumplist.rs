//! Windows taskbar jump list: the games and pages on the taskbar button's
//! right-click menu.
//!
//! This is the taskbar twin of the tray menu (`tray.rs`). Steam shows the same
//! two things there — the games you played last, and quick links into the app —
//! so the button is useful without opening the window first.
//!
//! Windows has no API to push an update into a running app from a jump list
//! entry: every entry re-runs the executable with a flag (`--gv-launch-game`
//! / `--gv-navigate`). `tauri-plugin-single-instance` forwards those arguments
//! to the running instance, which queues them as a [`crate::tray::TrayAction`].
//!
//! Only Windows has jump lists, so both entry points become no-ops elsewhere.

#[cfg(windows)]
mod windows_impl {
  use std::path::Path;

  use windows::core::{GUID, Interface, HSTRING, PWSTR};
  use windows::Win32::Foundation::PROPERTYKEY;
  use windows::Win32::System::Com::StructuredStorage::{
    PropVariantClear, PROPVARIANT, PROPVARIANT_0, PROPVARIANT_0_0, PROPVARIANT_0_0_0,
  };
  use windows::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CoTaskMemAlloc, CLSCTX_INPROC_SERVER,
    COINIT_APARTMENTTHREADED,
  };
  use windows::Win32::System::Variant::VT_LPWSTR;
  use windows::Win32::UI::Shell::Common::{IObjectArray, IObjectCollection};
  use windows::Win32::UI::Shell::PropertiesSystem::IPropertyStore;
  use windows::Win32::UI::Shell::{
    DestinationList, ICustomDestinationList, IShellLinkW, SetCurrentProcessExplicitAppUserModelID,
    ShellLink,
  };

  /// `PKEY_Title` (`System.Title`), which is the property the jump list uses as
  /// the entry's label.
  const PKEY_TITLE: PROPERTYKEY = PROPERTYKEY {
    fmtid: GUID::from_u128(0xf29f85e0_4ff9_1068_ab91_08002b27b3d9),
    pid: 2,
  };

  /// `CLSID_EnumerableObjectCollection`. The interface is generated by
  /// windows-rs, but this coclass is not.
  const ENUMERABLE_OBJECT_COLLECTION: GUID =
    GUID::from_u128(0x2d3468c1_36a7_43b6_ac24_d3f02fd9607a);

  /// Name of the "recently used" category in the jump list.
  const RECENT_CATEGORY: &str = "Recent";

  /// Gives the process an explicit AppUserModelID.
  ///
  /// Windows groups taskbar buttons by this id, and a jump list only shows on
  /// the button whose id matches the list. Without it Windows invents an id
  /// from the executable path, which a jump list cannot address reliably.
  pub(super) fn set_process_app_id(app_id: &str) -> windows::core::Result<()> {
    unsafe { SetCurrentProcessExplicitAppUserModelID(&HSTRING::from(app_id)) }
  }

  /// Replaces the games category and the task list with `recent` and `pages`.
  pub(super) fn update(app_id: &str, recent: &[(i64, String)], pages: &[&str]) -> windows::core::Result<()> {
    let executable = std::env::current_exe()?;
    unsafe { update_inner(app_id, &executable, recent, pages) }
  }

  unsafe fn update_inner(
    app_id: &str,
    executable: &Path,
    recent: &[(i64, String)],
    pages: &[&str],
  ) -> windows::core::Result<()> {
    // The caller runs this on the main thread, where the event loop already put
    // us in a COM apartment. Asking again is harmless and keeps the list from
    // silently doing nothing if that ever changes.
    let _ = CoInitializeEx(None, COINIT_APARTMENTTHREADED);

    let list: ICustomDestinationList =
      CoCreateInstance(&DestinationList, None, CLSCTX_INPROC_SERVER)?;
    list.SetAppID(&HSTRING::from(app_id))?;

    // `BeginList` starts an editing session and reports how many entries the
    // user's "recent items" setting allows; anything more is discarded.
    let mut minimum_slots = 0u32;
    let _removed: IObjectArray = list.BeginList(&mut minimum_slots)?;

    if !recent.is_empty() {
      let games = object_collection()?;
      for (game_id, title) in recent {
        games.AddObject(&game_shortcut(executable, *game_id, title)?)?;
      }
      let games: IObjectArray = games.cast()?;
      list.AppendCategory(&HSTRING::from(RECENT_CATEGORY), &games)?;
    }

    let tasks = object_collection()?;
    for page in pages {
      tasks.AddObject(&page_shortcut(executable, page)?)?;
    }
    let tasks: IObjectArray = tasks.cast()?;
    list.AddUserTasks(&tasks)?;

    list.CommitList()
  }

  unsafe fn object_collection() -> windows::core::Result<IObjectCollection> {
    CoCreateInstance(&ENUMERABLE_OBJECT_COLLECTION, None, CLSCTX_INPROC_SERVER)
  }

  unsafe fn shell_link() -> windows::core::Result<IShellLinkW> {
    CoCreateInstance(&ShellLink, None, CLSCTX_INPROC_SERVER)
  }

  /// A jump list entry that re-runs GameVault and asks it to launch a game.
  unsafe fn game_shortcut(
    executable: &Path,
    game_id: i64,
    title: &str,
  ) -> windows::core::Result<IShellLinkW> {
    shortcut(
      executable,
      &format!("{} {game_id}", crate::tray::ARG_LAUNCH_GAME),
      title,
    )
  }

  /// A jump list entry that re-runs GameVault and asks it to open a page.
  unsafe fn page_shortcut(
    executable: &Path,
    page: &str,
  ) -> windows::core::Result<IShellLinkW> {
    let title = crate::tray::page_title(page);
    shortcut(
      executable,
      &format!("{} {page}", crate::tray::ARG_NAVIGATE),
      &title,
    )
  }

  unsafe fn shortcut(
    executable: &Path,
    arguments: &str,
    title: &str,
  ) -> windows::core::Result<IShellLinkW> {
    let link = shell_link()?;
    link.SetPath(&HSTRING::from(executable.as_os_str()))?;
    link.SetArguments(&HSTRING::from(arguments))?;
    link.SetDescription(&HSTRING::from(title))?;
    set_title(&link, title)?;
    Ok(link)
  }

  /// Sets `System.Title` on the link — without it the jump list entry falls
  /// back to the executable's own name for every game.
  unsafe fn set_title(link: &IShellLinkW, title: &str) -> windows::core::Result<()> {
    let store: IPropertyStore = link.cast()?;
    let mut value = title_prop_variant(title);
    let set = store.SetValue(&PKEY_TITLE, &value);
    let _ = PropVariantClear(&mut value);
    set?;
    store.Commit()
  }

  /// A `VT_LPWSTR` PROPVARIANT. Windows takes ownership of the string, so it
  /// has to come from the COM task allocator.
  fn title_prop_variant(title: &str) -> PROPVARIANT {
    let wide: Vec<u16> = title.encode_utf16().chain(std::iter::once(0)).collect();
    let memory = unsafe { CoTaskMemAlloc(wide.len() * std::mem::size_of::<u16>()) as *mut u16 };
    if memory.is_null() {
      // A named entry is nicer, but an unnamed one still launches the game.
      return PROPVARIANT::default();
    }
    unsafe { std::ptr::copy_nonoverlapping(wide.as_ptr(), memory, wide.len()) };

    PROPVARIANT {
      Anonymous: PROPVARIANT_0 {
        Anonymous: std::mem::ManuallyDrop::new(PROPVARIANT_0_0 {
          vt: VT_LPWSTR,
          wReserved1: 0,
          wReserved2: 0,
          wReserved3: 0,
          Anonymous: PROPVARIANT_0_0_0 {
            pwszVal: PWSTR(memory),
          },
        }),
      },
    }
  }
}

/// Gives the process an explicit AppUserModelID so its jump list can be
/// attached to its taskbar button.
#[cfg(windows)]
pub(crate) fn set_process_app_id(app_id: &str) {
  if let Err(error) = windows_impl::set_process_app_id(app_id) {
    log::warn!("could not set the AppUserModelID: {error}");
  }
}

/// No-op: only Windows has jump lists.
#[cfg(not(windows))]
pub(crate) fn set_process_app_id(_app_id: &str) {}

/// Replaces the jump list's games category and task list.
///
/// Must be called on the main thread, where the event loop owns the COM
/// apartment.
#[cfg(windows)]
pub(crate) fn update(app_id: &str, recent: &[(i64, String)]) {
  if let Err(error) = windows_impl::update(app_id, recent, &crate::tray::PAGES) {
    log::warn!("could not update the taskbar jump list: {error}");
  }
}

/// No-op: only Windows has jump lists.
#[cfg(not(windows))]
pub(crate) fn update(_app_id: &str, _recent: &[(i64, String)]) {}
